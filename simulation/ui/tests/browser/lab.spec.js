import { test, expect } from '@playwright/test';

test('local React lab controls the Python engine and renders every canonical family', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('Python engine connected', { exact: true })).toBeVisible();
  await expect(page.locator('.signal-card')).toHaveCount(9);
  await expect(page.getByTestId('family-blood_sugar')).toContainText('mmol/L');
  await expect(page.getByTestId('family-body_temperature')).toContainText('Cel');
  await expect(page.getByTestId('family-muscle')).toContainText('kgf');
  await expect(page.getByTestId('family-muscle')).toContainText('kg');
  await expect(page.getByTestId('family-bone_mineral_density')).toContainText('g/cm2');
  await expect(page.getByTestId('family-cumulative_absorbed_radiation_dose')).toContainText('mGy');
  await page.getByRole('button', { name: '▶ Start', exact: true }).click();
  await expect(page.getByTestId('simulation-status')).toHaveText('RUNNING');
  await expect(page.getByTestId('reading-heart_rate-value')).not.toHaveText('—');
  await page.getByRole('button', { name: 'Ⅱ Pause', exact: true }).click();
  await expect(page.getByTestId('simulation-status')).toHaveText('PAUSED');
  const time = await page.getByTestId('virtual-time').textContent();
  const count = await page.getByTestId('retained-count').textContent();
  await page.waitForTimeout(1100);
  expect(await page.getByTestId('virtual-time').textContent()).toBe(time);
  expect(await page.getByTestId('retained-count').textContent()).toBe(count);
  // Control input changes are deliberately applied, and reach the Python configuration.
  await page.getByRole('slider', { name: 'Stress', exact: true }).focus();
  await page.keyboard.press('Home');
  for (let i = 0; i < 16; i++) await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Apply parameters' }).click();
  const state = await (await page.request.get('/api/state')).json();
  expect(state.settings.stress).toBe(0.8);
  await page.getByLabel('Time acceleration').selectOption('3600');
  await page.getByRole('button', { name: 'Apply parameters' }).click();
  expect((await (await page.request.get('/api/state')).json()).settings.time_scale).toBe(3600);
  await page.getByRole('button', { name: '↗ Resume', exact: true }).click();
  await expect(page.getByTestId('simulation-status')).toHaveText('RUNNING');
  await page.getByRole('button', { name: '+28 days', exact: true }).click();
  await expect(page.getByTestId('reading-bone_mineral_density-areal_density')).not.toHaveText('—');
  await page.getByRole('button', { name: /Exercise/ }).click();
  const exercise = await (await page.request.get('/api/state')).json();
  expect(exercise.settings.scenario).toBe('exercise');
  expect(exercise.state).toBe('RUNNING');
  await page.getByRole('button', { name: 'Ⅱ Pause', exact: true }).click();
  await expect(page.getByTestId('simulation-status')).toHaveText('PAUSED');
  await page.getByLabel('Fictional astronaut').selectOption({ label: 'Tomas Reyes' });
  await expect(page.getByRole('heading', { name: /Tomas’s signals/ })).toBeVisible();
  await expect(page.getByTestId('reading-bone_mineral_density-areal_density')).not.toHaveText('—');
  await page.screenshot({ path: 'test-results/lab-populated-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/lab-populated-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const oldRun = await page.getByTestId('run-id').textContent();
  const before = await (await page.request.get('/api/state')).json();
  await page.getByRole('button', { name: '↺ Reset', exact: true }).click();
  await expect(page.getByTestId('run-id')).not.toHaveText(oldRun);
  await expect(page.getByTestId('simulation-status')).toHaveText('READY');
  const reset = await (await page.request.get('/api/state')).json();
  expect(reset.retained_observations).toBe(before.retained_observations);
  expect(reset.origin).toBe(before.virtual_at);
  await page.getByLabel('View run').selectOption(oldRun);
  await expect(page.getByText('Viewing a retained run.', { exact: false })).toBeVisible();
  await expect(page.getByTestId('reading-bone_mineral_density-areal_density')).not.toHaveText('—');
  await page.getByRole('button', { name: 'Return to current run →' }).click();
  await expect(page.getByTestId('reading-bone_mineral_density-areal_density')).toHaveText('—');
  await page.screenshot({ path: 'test-results/lab-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Simulation lab.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/lab-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
